#!/usr/bin/env python3
"""Generate (but do not submit) the Slurm array-job sbatch script for the
Phase-12 campaign. Writes a single .sbatch file to disk; never calls
`sbatch`, `srun`, or any other job-submission command. Every array task
invokes `run_phase12_campaign_shard.py` in its default `--dry-run` mode
(Phase-12C must explicitly change this to `--execute` after its own
review -- this generator does not do so).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

DEFAULT_SHARD_PLAN = REPO_ROOT / "artifacts/manifests/ranking_portability_phase12_shard_plan.json"
DEFAULT_OUT = REPO_ROOT / "artifacts/phase12_campaign.sbatch"

TEMPLATE = """#!/bin/bash
#SBATCH --job-name=lssp-phase12-campaign
#SBATCH --array=0-{max_shard_index}
#SBATCH --time=02:00:00
#SBATCH --cpus-per-task=1
#SBATCH --mem=4G
#SBATCH --output=artifacts/phase12_campaign_logs/shard_%a.out
#SBATCH --error=artifacts/phase12_campaign_logs/shard_%a.err

# GENERATED FILE -- not submitted by anything in this repository state.
# Generated by scripts/ranking_portability/generate_phase12_sbatch.py from
# shard plan campaign_manifest_freeze_sha256={freeze_sha}.
# shard_count={shard_count}, total_cells={total_cells},
# estimated total cost {total_hours:.2f} CPU-hours (see the shard plan for
# per-shard estimates; this is a wall-clock planning figure, not a
# scientific-outcome-derived value).
#
# Every array task runs the shard entrypoint in --dry-run mode (the
# default). Phase-12C must deliberately change this line to --execute
# after implementing and reviewing the real per-cell execution loop.

module load {module_load}

PYTHONPATH=src {python_bin} scripts/ranking_portability/run_phase12_campaign_shard.py \\
  --shard-id "${{SLURM_ARRAY_TASK_ID}}" \\
  --manifest artifacts/manifests/ranking_portability_phase12_campaign_freeze.json \\
  --shard-plan artifacts/manifests/ranking_portability_phase12_shard_plan.json \\
  --dry-run
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--shard-plan", type=Path, default=DEFAULT_SHARD_PLAN)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--module-load", default="slurm/wulver")
    ap.add_argument(
        "--python-bin", default="python3",
        help="Interpreter to invoke in the generated sbatch script "
             "(point this at your own cluster venv, e.g. .venv/bin/python)",
    )
    args = ap.parse_args()

    with open(args.shard_plan) as f:
        plan = json.load(f)

    script = TEMPLATE.format(
        max_shard_index=plan["shard_count"] - 1,
        freeze_sha=plan["campaign_manifest_freeze_sha256"],
        shard_count=plan["shard_count"],
        total_cells=plan["total_cells"],
        total_hours=plan["total_estimated_cost_seconds"] / 3600,
        module_load=args.module_load,
        python_bin=args.python_bin,
    )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(script)
    print(f"wrote {args.out} ({len(script)} bytes)")
    print("SBATCH_GENERATED_NOT_SUBMITTED = YES")


if __name__ == "__main__":
    main()
